/**
 * Generates public/_headers and public/_redirects for Cloudflare.
 *
 * Next.js' headers() and redirects() config does not run in a static export
 * (next.config.ts sets output: "export"), so the same rules are emitted here as
 * Cloudflare static config files. Next copies everything in public/ into out/
 * verbatim, and Cloudflare's asset hosting reads both files from there.
 *
 * Run `npm run cf:config` after changing a rule; `npm run build` runs it first.
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const publicDir = join(root, "public");
mkdirSync(publicDir, { recursive: true });

const headers = `# Generated by scripts/build-cloudflare-static-config.mjs - do not edit by hand.
# Mirrors the headers() block next.config.ts used on Vercel.
/*
  X-Frame-Options: SAMEORIGIN
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=()
  Strict-Transport-Security: max-age=63072000; includeSubDomains; preload
  Content-Security-Policy: default-src 'self'; script-src 'self' 'unsafe-inline' 'unsafe-eval' *.googletagmanager.com *.google-analytics.com *.clarity.ms; img-src 'self' data: https:; font-src 'self' data:; connect-src 'self' *.google-analytics.com *.supabase.co *.clarity.ms; style-src 'self' 'unsafe-inline'; frame-ancestors 'self';
  Cross-Origin-Opener-Policy: same-origin-allow-popups

# Hashed build assets never change under the same URL.
/_next/static/*
  Cache-Control: public, max-age=31536000, immutable

# next/og writes these three as extensionless files, so Cloudflare serves them
# with no Content-Type at all. Combined with nosniff above, browsers refuse to
# render the favicon and social crawlers refuse the OG image, so declare it here.
/icon
  Content-Type: image/png
/apple-icon
  Content-Type: image/png
/opengraph-image
  Content-Type: image/png
`;

// Same list the old next.config.ts redirects() held. The non-www -> www rule is
// NOT here: Cloudflare matches _redirects on path only, so it is configured as a
// Redirect Rule on the zone instead (see README).
const redirects = [
  ["/about", "/about-us"],
  // /author has no listing page; send it to the about page rather than 404.
  ["/author", "/about-us"],
];

const lines = [
  "# Generated by scripts/build-cloudflare-static-config.mjs - do not edit by hand.",
  "# Mirrors the redirects() block next.config.ts used on Vercel.",
  "# The non-www -> www redirect is NOT here: Cloudflare matches on path only,",
  "# so set it as a Redirect Rule / Bulk Redirect on the zone.",
  "",
  ...redirects.map(([from, to]) => `${from} ${to} 301`),
  "",
];

writeFileSync(join(publicDir, "_headers"), headers);
writeFileSync(join(publicDir, "_redirects"), lines.join("\n"));
console.log(`Wrote public/_headers and public/_redirects (${redirects.length} redirects).`);
